// bitReverse maps each byte to its bit-reversed form. Teletext data in MPEG-TS
// is stored MSB-first but the teletext standard transmits LSB-first.
var bitReverse [256]byte

func init() {
	for i := 0; i < 256; i++ {
		var r byte
		for bit := 0; bit < 8; bit++ {
			r |= ((byte(i) >> bit) & 1) << (7 - bit)
		}
		bitReverse[i] = r
	}
}

